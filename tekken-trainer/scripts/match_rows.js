// Turn input-history rows (from read_input_history.py) into timed runs, and find which
// trainer combos and drills each run performs. Prints a report and writes
// js/data/pro-timing.js with the frame gaps of every matched run.
//
//   node scripts/match_rows.js ROWS.json DUPES.json "Source name" OUT.js
//
// DUPES.json (optional, "-" to skip) has per-frame differences; runs with many repeated
// frames are slow motion and are skipped.
"use strict";
const fs = require("node:fs");
const path = require("node:path");

globalThis.window = globalThis;
require(path.join(__dirname, "../js/data/combos.js"));
const { parse, Matcher } = require(path.join(__dirname, "../js/engine.js"));

const [rowsFile, dupesFile, source, outFile] = process.argv.slice(2);
if (!rowsFile || !source || !outFile) {
  console.error("usage: node scripts/match_rows.js ROWS.json DUPES.json|- SOURCE OUT.js");
  process.exit(2);
}
const rows = JSON.parse(fs.readFileSync(rowsFile, "utf8"));
const diffs = dupesFile && dupesFile !== "-" ? JSON.parse(fs.readFileSync(dupesFile, "utf8")).diff : null;
const TIMING = { justFrames: T8_TIMING.justFrames, fastWR: T8_TIMING.fastWR };
const IDLE = 120;         // a neutral row this long (2 s) ends a run
const FPS = 60;

// Split rows into runs at long idle rows.
const runs = [];
let cur = [];
for (const r of rows) {
  if (r.dir === "n" && !r.btn.length && r.n >= IDLE) {
    if (cur.length) runs.push(cur);
    cur = [];
  } else {
    cur.push(r);
  }
}
if (cur.length) runs.push(cur);

function slowRatio(run) {
  if (!diffs) return 0;
  const a = Math.round(run[0].t * FPS);
  const b = Math.round(run[run.length - 1].t * FPS) + run[run.length - 1].n;
  let dup = 0;
  for (let i = a; i < b && i < diffs.length; i++) if (diffs[i] < 0.4) dup++;
  return dup / Math.max(1, b - a);
}

// Rows -> engine events (frame numbers start at 0 for the run).
function toEvents(run) {
  const ev = [];
  let f = 0, held = new Set(), dir = "n";
  for (const r of run) {
    const d = r.dir === "?" ? dir : r.dir;
    if (d !== dir) { ev.push({ f, type: "dir", dir: d }); dir = d; }
    const now = new Set(r.btn);
    for (const b of now) if (!held.has(b)) ev.push({ f, type: "press", btn: b });
    held = now;
    f += r.n;
  }
  return { ev, len: f };
}

function label(run) {
  return run.map((r) => (r.dir === "n" ? "" : r.dir) + (r.btn.length ? (r.dir === "n" ? "" : "+") + r.btn.join("+") : "") + ":" + r.n)
    .map((s) => (s.startsWith(":") ? "n" + s : s)).join(" ");
}

// Try every start press: a combo can begin after some movement in the run.
function tryMatch(item, events) {
  let steps;
  try { steps = parse(item.notation, TIMING); } catch { return null; }
  const starts = events.map((e, i) => i).filter((i) => events[i].type === "press" || i === 0);
  for (const s of starts) {
    const m = new Matcher(steps, { simulWindow: 2, stringWindow: 60, moveWindow: 90, tildeWindow: 12, motionWindow: 24 });
    // Seed the direction held before the start.
    let lastDir = { f: -1e9, d: "n" };
    for (let i = 0; i < s; i++) if (events[i].type === "dir") lastDir = { f: events[i].f, d: events[i].dir };
    m.hist = [lastDir];
    for (let i = s; i < events.length && m.state !== "done" && m.state !== "fail"; i++) {
      const e = events[i];
      if (e.type === "dir") m.dir(e.f, e.dir); else m.press(e.f, e.btn);
    }
    if (m.state === "done") return { start: s, gaps: m.results.map((r) => r.gap) };
  }
  return null;
}

const items = [...T8_COMBOS, ...T8_DRILLS];
const out = {};
let used = 0, slow = 0;
runs.forEach((run, i) => {
  const sr = slowRatio(run);
  const unsure = run.filter((r) => r.dir === "?" || r.sure === false).length;
  const { ev } = toEvents(run);
  const hits = [];
  if (sr > 0.35) slow++;
  else for (const it of items) {
    const m = tryMatch(it, ev);
    if (m) hits.push({ id: it.id, gaps: m.gaps });
  }
  console.log(`#${i} t=${run[0].t}s rows=${run.length} slow=${sr.toFixed(2)} unsure=${unsure}` +
    (sr > 0.35 ? " SKIPPED (slow motion)" : "") +
    `\n   ${label(run)}` + (hits.length ? `\n   matches: ${hits.map((h) => h.id + " [" + h.gaps.join(",") + "]").join("  ")}` : ""));
  for (const h of hits) {
    (out[h.id] = out[h.id] || []).push({ gaps: h.gaps, t: run[0].t, source });
    used++;
  }
});
console.log(`\n${runs.length} runs, ${slow} slow-motion skipped, ${used} matches, ${Object.keys(out).length} combos/drills with pro timing`);

const prev = fs.existsSync(outFile)
  ? JSON.parse(fs.readFileSync(outFile, "utf8").replace(/^[\s\S]*?window\.T8_PRO_TIMING = /, "").replace(/;\s*$/, ""))
  : {};
for (const [id, list] of Object.entries(out)) {
  prev[id] = (prev[id] || []).filter((x) => x.source !== source).concat(list);
}
fs.writeFileSync(outFile,
  "// Frame gaps of combos done by players in videos (read from Tekken 8's input history).\n" +
  "// Generated by scripts/match_rows.js. Do not edit by hand.\n" +
  "window.T8_PRO_TIMING = " + JSON.stringify(prev) + ";\n");
