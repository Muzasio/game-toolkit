#!/usr/bin/env python3
"""Build the trainer's data files from TekkenDocs frame data JSON.

Download first (one request per second, be polite):
    curl -A "Mozilla/5.0" -o chars/<name>.json https://tekkendocs.com/api/t8/<name>/framedata

Then run:
    python3 -I scripts/build_data.py <chars_dir> <output_js_dir>

Frame data credit: TekkenDocs (https://tekkendocs.com), which asks for
attribution wherever its data is shown.
"""
import json
import re
import sys
from pathlib import Path

MAIN = "dragunov"
NAME_RE = re.compile(r"^[a-z0-9-]{1,32}$")
INT_RE = re.compile(r"^\s*([+-]?\d+)\s*([a-zA-Z]*)\s*$")


def clean(s, limit=400):
    """Keep only short plain strings (no control chars)."""
    if not isinstance(s, str):
        return ""
    s = "".join(ch for ch in s if ch == "\n" or ch >= " ")
    return s.strip()[:limit]


def first_startup(s):
    m = re.match(r"\s*i(\d+)", clean(s))
    return int(m.group(1)) if m else None


def block_value(s):
    """Return block frames as int, or None when it is a range or unclear."""
    m = INT_RE.match(clean(s))
    return int(m.group(1)) if m else None


def load(path):
    with path.open(encoding="utf-8") as f:
        data = json.load(f)
    moves = data.get("framesNormal")
    if not isinstance(moves, list):
        raise ValueError(f"{path.name}: no framesNormal list")
    return moves


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]).resolve()
    out.mkdir(parents=True, exist_ok=True)

    files = sorted(p for p in src.glob("*.json") if NAME_RE.match(p.stem))

    # Dragunov: full move list for the move guide.
    main_moves = []
    for m in load(src / f"{MAIN}.json"):
        main_moves.append({k: clean(m.get(k, "")) for k in
                           ("command", "name", "hitLevel", "damage", "startup",
                            "block", "hit", "counterHit", "notes")})

    # Every character: moves you can punish (or must block) for the punish trainer.
    punish = []
    for p in files:
        for m in load(p):
            cmd = clean(m.get("command"), 60)
            level = clean(m.get("hitLevel"), 40).replace(" ", "")
            blk = block_value(m.get("block", ""))
            start = first_startup(m.get("startup", ""))
            if not cmd or blk is None or start is None or not level:
                continue
            if cmd.startswith(("R.", "H.")) or "t" in level.lower().split(",")[-1]:
                continue  # rage arts, heat-only moves, throws
            if blk < -20 or blk > 0:
                continue
            punish.append({"c": p.stem, "cmd": cmd, "n": clean(m.get("name"), 60),
                           "lv": level, "i": start, "b": blk})

    def write(name, var, obj):
        text = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
        (out / name).write_text(
            f"// Generated by scripts/build_data.py from TekkenDocs frame data "
            f"(https://tekkendocs.com). Do not edit by hand.\n"
            f"window.{var} = {text};\n", encoding="utf-8")
        print(f"{name}: {len(obj)} entries")

    write("moves-dragunov.js", "T8_MOVES", main_moves)
    write("punish-targets.js", "T8_PUNISH", punish)


if __name__ == "__main__":
    main()
